/*
  Asignación Académica · CECAR — migración inicial (SPEC-002, SPEC-011).
  Se aplica con `npx prisma migrate deploy`; los catálogos los carga
  `npx prisma db seed` (prisma/seed.ts, desde src/lib/catalogos.ts).

  Refleja el dominio de src/lib/tipos.ts y src/lib/novedades.ts. Los
  identificadores son UUID porque la aplicación ya los genera así: los datos
  de un respaldo JSON migran sin cambiar sus ids.

  Lo que el esquema impone por sí mismo, sin confiar en la aplicación:
    · la cascada contrato → dedicación → categoría (SPEC-001), por FK;
    · los estados del ciclo de vida, por CHECK;
    · que la bitácora y las novedades solo admitan INSERT, por trigger.
  Prisma no expresa nada de esto en schema.prisma: por eso este archivo es
  SQL escrito a mano y nunca se usa `prisma db push`.

  Diferencias deliberadas con la versión SQL Server:
    · Sin intercalación insensible a mayúsculas: la aplicación compara con
      los valores exactos del catálogo y guarda el correo en minúsculas.
    · %%physloc%% no existe: el orden de inserción de la bitácora y de la
      foto de impacto lo da la columna `secuencia`.
*/


CREATE SCHEMA IF NOT EXISTS aa;

/* ─────────────────────────── Catálogo académico ─────────────────────────── */

CREATE TABLE aa.facultad (
  codigo  VARCHAR(80)  NOT NULL CONSTRAINT pk_facultad PRIMARY KEY  -- 'CIENCIAS_BÁSICAS_INGENIERÍAS_Y_ARQUITECTURA'
);

CREATE TABLE aa.programa (
  id        INT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_programa PRIMARY KEY,
  nombre    VARCHAR(120) NOT NULL CONSTRAINT uq_programa_nombre UNIQUE,
  facultad  VARCHAR(80)  NOT NULL CONSTRAINT fk_programa_facultad REFERENCES aa.facultad (codigo),
  codigo    VARCHAR(10)  NULL      -- no todos los programas del formato traen código
);

/* ───────────────────── Cascada de vinculación (SPEC-001) ─────────────────── */

CREATE TABLE aa.tipo_contrato (
  codigo VARCHAR(40) NOT NULL CONSTRAINT pk_tipo_contrato PRIMARY KEY
);

CREATE TABLE aa.dedicacion (
  codigo VARCHAR(40) NOT NULL CONSTRAINT pk_dedicacion PRIMARY KEY
);

CREATE TABLE aa.categoria (
  codigo VARCHAR(40) NOT NULL CONSTRAINT pk_categoria PRIMARY KEY
);

/*
  Las combinaciones que admite el formato oficial. En el Excel la categoría
  depende solo de la dedicación (INDIRECT($J9)); se guarda la terna completa
  para que la FK del docente valide las tres columnas a la vez y para admitir,
  si algún día se diferencian, escalafones distintos por contrato.
*/
CREATE TABLE aa.contrato_dedicacion_categoria (
  tipo_contrato VARCHAR(40) NOT NULL CONSTRAINT fk_cdc_contrato   REFERENCES aa.tipo_contrato (codigo),
  dedicacion    VARCHAR(40) NOT NULL CONSTRAINT fk_cdc_dedicacion REFERENCES aa.dedicacion (codigo),
  categoria     VARCHAR(40) NOT NULL CONSTRAINT fk_cdc_categoria  REFERENCES aa.categoria (codigo),
  CONSTRAINT pk_contrato_dedicacion_categoria PRIMARY KEY (tipo_contrato, dedicacion, categoria)
);

/* ──────────────────────────── Parametrización ───────────────────────────── */

CREATE TABLE aa.regla_dedicacion (
  dedicacion  VARCHAR(40) NOT NULL CONSTRAINT pk_regla_dedicacion PRIMARY KEY
                                   CONSTRAINT fk_regla_dedicacion REFERENCES aa.dedicacion (codigo),
  max_horas   SMALLINT NOT NULL CONSTRAINT ck_regla_max  CHECK (max_horas   >= 0),
  preparacion SMALLINT NOT NULL CONSTRAINT ck_regla_prep CHECK (preparacion >= 0),
  atencion    SMALLINT NOT NULL CONSTRAINT ck_regla_aten CHECK (atencion    >= 0),
  comunidades SMALLINT NOT NULL CONSTRAINT ck_regla_com  CHECK (comunidades >= 0)
);

/* Una sola fila: los límites son globales. */
CREATE TABLE aa.limite (
  id                  SMALLINT NOT NULL CONSTRAINT pk_limite PRIMARY KEY CONSTRAINT ck_limite_unico CHECK (id = 1),
  max_cursos          SMALLINT NOT NULL CONSTRAINT ck_limite_cursos CHECK (max_cursos >= 1),
  max_descargas       SMALLINT NOT NULL CONSTRAINT ck_limite_desc   CHECK (max_descargas >= 1),
  max_administrativas SMALLINT NOT NULL CONSTRAINT ck_limite_adm    CHECK (max_administrativas >= 1)
);

/*
  Id explícito, no IDENTITY: los roles 1..56 son los del formato y las
  asignaciones los referencian por número.
*/
CREATE TABLE aa.rol (
  id            INT          NOT NULL CONSTRAINT pk_rol PRIMARY KEY,
  nombre        VARCHAR(150) NOT NULL CONSTRAINT uq_rol_nombre UNIQUE,
  tipo          VARCHAR(15)  NOT NULL CONSTRAINT ck_rol_tipo CHECK (tipo IN ('DOCENCIA', 'INVESTIGACION', 'EXTENSION')),
  -- Roles 49–56: fuera de todo rango SUMIF en el Excel; sus horas se perdían.
  reclasificado BOOLEAN      NOT NULL DEFAULT FALSE,
  /*
    Eliminar un rol en la aplicación lo quita de la lista, pero las
    asignaciones ya cerradas lo siguen referenciando: aquí se marca como no
    vigente en vez de borrarse.
  */
  vigente       BOOLEAN      NOT NULL DEFAULT TRUE
);

/* ─────────────────────────── Usuarios y periodos ────────────────────────── */

CREATE TABLE aa.usuario (
  id          UUID         NOT NULL DEFAULT gen_random_uuid() CONSTRAINT pk_usuario PRIMARY KEY,
  email       VARCHAR(254) NOT NULL CONSTRAINT uq_usuario_email UNIQUE,
  nombres     VARCHAR(150) NOT NULL,
  rol         VARCHAR(12)  NOT NULL CONSTRAINT ck_usuario_rol CHECK (rol IN ('ADMIN', 'COORDINADOR')),
  -- El programa que gestiona un coordinador; el administrador no tiene.
  programa_id INT          NULL CONSTRAINT fk_usuario_programa REFERENCES aa.programa (id),
  activo      BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE aa.periodo (
  codigo CHAR(6) NOT NULL CONSTRAINT pk_periodo PRIMARY KEY
                          CONSTRAINT ck_periodo_formato CHECK (codigo ~ '^[12][0-9]{3}-[12]$')  -- '2026-2'
);

/* Una convocatoria por periodo. El límite ya viene a las 23:59 (finDelDia). */
CREATE TABLE aa.convocatoria (
  periodo             CHAR(6)     NOT NULL CONSTRAINT pk_convocatoria PRIMARY KEY
                                           CONSTRAINT fk_convocatoria_periodo REFERENCES aa.periodo (codigo),
  apertura            TIMESTAMPTZ NOT NULL,
  limite              TIMESTAMPTZ NOT NULL,
  cerrada_manualmente BOOLEAN     NOT NULL DEFAULT FALSE,
  CONSTRAINT ck_convocatoria_fechas CHECK (limite > apertura)
);

/* ────────────────────────────── Asignaciones ────────────────────────────── */

CREATE TABLE aa.asignacion (
  id                UUID        NOT NULL CONSTRAINT pk_asignacion PRIMARY KEY,
  periodo           CHAR(6)     NOT NULL CONSTRAINT fk_asignacion_periodo REFERENCES aa.periodo (codigo),
  programa_id       INT         NOT NULL CONSTRAINT fk_asignacion_programa REFERENCES aa.programa (id),
  estado            VARCHAR(15) NOT NULL CONSTRAINT ck_asignacion_estado
                      CHECK (estado IN ('borrador', 'enviada', 'en_revision', 'aprobada', 'en_correccion')),
  -- Cuántas veces se ha enviado: v2 significa que hubo una devolución.
  version           INT         NOT NULL DEFAULT 0 CONSTRAINT ck_asignacion_version CHECK (version >= 0),
  -- Solo aplica en en_correccion.
  plazo_correccion  TIMESTAMPTZ NULL,
  -- La línea base de la proyección (SPEC-009): cuándo se aprobó por primera
  -- vez y qué versión. NULL en lo aprobado antes de SPEC-009 y en lo no aprobado.
  linea_base_fecha   TIMESTAMPTZ NULL,
  linea_base_version INT         NULL,
  creada            TIMESTAMPTZ NOT NULL,
  actualizada       TIMESTAMPTZ NOT NULL,
  -- La concurrencia la resuelve `SELECT … FOR UPDATE` en lib/servidor/escribir.ts.
  CONSTRAINT ck_asignacion_plazo CHECK (plazo_correccion IS NULL OR estado = 'en_correccion')
  /*
    Pendiente con el cliente: ¿una sola asignación por programa y periodo?
    Si es así:  CONSTRAINT uq_asignacion_programa_periodo UNIQUE (programa_id, periodo)
  */
);

/* La persona, identificada por documento. Habilita el histórico por docente. */
CREATE TABLE aa.docente (
  id        UUID         NOT NULL DEFAULT gen_random_uuid() CONSTRAINT pk_docente PRIMARY KEY,
  documento VARCHAR(15)  NOT NULL CONSTRAINT uq_docente_documento UNIQUE
                                  CONSTRAINT ck_docente_documento CHECK (documento ~ '^[0-9]{6,}$'),
  nombres   VARCHAR(150) NOT NULL
);

/*
  La vinculación de un docente en una asignación: lo que el formato captura
  por periodo. El id es el del Docente de la aplicación.

  Casi todo admite NULL a propósito: un borrador tiene docentes a medio
  llenar, y la base tiene que poder guardarlo. La base impone la coherencia
  de lo que está lleno —la cascada, los rangos—; la completitud la exige el
  motor de la aplicación (validarDocente) antes de dejar enviar.

  documento y nombres se guardan como se escribieron en ese periodo;
  docente_id enlaza a la persona cuando el documento ya es válido.
*/
CREATE TABLE aa.docente_asignado (
  id                     UUID         NOT NULL CONSTRAINT pk_docente_asignado PRIMARY KEY,
  asignacion_id          UUID         NOT NULL CONSTRAINT fk_da_asignacion REFERENCES aa.asignacion (id) ON DELETE CASCADE,
  docente_id             UUID         NULL CONSTRAINT fk_da_docente REFERENCES aa.docente (id),
  orden                  SMALLINT     NOT NULL,
  documento              VARCHAR(15)  NULL,
  nombres                VARCHAR(150) NULL,
  nivel_formacion        VARCHAR(30)  NULL,
  perfil_profesional     TEXT         NULL,
  categoria_minciencias  VARCHAR(20)  NULL,
  activo_sector_externo  CHAR(2)      NULL CONSTRAINT ck_da_activo CHECK (activo_sector_externo IN ('SI', 'NO')),
  sector_ejerce          VARCHAR(60)  NULL,
  tipo_contrato          VARCHAR(40)  NULL CONSTRAINT fk_da_contrato REFERENCES aa.tipo_contrato (codigo),
  dedicacion             VARCHAR(40)  NULL,
  categoria              VARCHAR(40)  NULL,
  sede                   VARCHAR(40)  NULL,
  evaluacion_docente     NUMERIC(3, 2) NULL CONSTRAINT ck_da_evaluacion CHECK (evaluacion_docente BETWEEN 0 AND 5),
  observaciones          TEXT         NULL,
  preparacion            NUMERIC(5, 1) NOT NULL CONSTRAINT ck_da_prep CHECK (preparacion >= 0),
  atencion               NUMERIC(5, 1) NOT NULL CONSTRAINT ck_da_aten CHECK (atencion    >= 0),
  comunidades            NUMERIC(5, 1) NOT NULL CONSTRAINT ck_da_com  CHECK (comunidades >= 0),
  /*
    SPEC-001: la terna tiene que existir en la cascada del formato. Con
    MATCH SIMPLE (el predeterminado) PostgreSQL no comprueba una FK compuesta
    si alguna columna es NULL: el borrador que aún no elige categoría pasa, y
    una terna completa inválida no.
  */
  CONSTRAINT fk_da_cascada FOREIGN KEY (tipo_contrato, dedicacion, categoria)
    REFERENCES aa.contrato_dedicacion_categoria (tipo_contrato, dedicacion, categoria),
  -- Puede faltar la categoría, pero no hay dedicación sin contrato.
  CONSTRAINT ck_da_orden_cascada CHECK (
    (dedicacion IS NULL OR tipo_contrato IS NOT NULL) AND (categoria IS NULL OR dedicacion IS NOT NULL))
);

/* La misma persona no va dos veces en una asignación. Parcial: UNIQUE a secas
   también lo haría (NULL no choca en PostgreSQL), pero así queda explícito. */
CREATE UNIQUE INDEX uq_da_docente_por_asignacion
  ON aa.docente_asignado (asignacion_id, docente_id) WHERE docente_id IS NOT NULL;

CREATE TABLE aa.curso_asignado (
  id                  UUID          NOT NULL CONSTRAINT pk_curso_asignado PRIMARY KEY,
  docente_asignado_id UUID          NOT NULL CONSTRAINT fk_curso_da REFERENCES aa.docente_asignado (id) ON DELETE CASCADE,
  orden               SMALLINT      NOT NULL,
  codigo_programa     VARCHAR(10)   NULL,
  nombre_programa     VARCHAR(120)  NULL,
  codigo_pensum       VARCHAR(20)   NULL,
  codigo_curso        VARCHAR(20)   NULL,
  nombre_curso        VARCHAR(150)  NULL,
  semestre            SMALLINT      NULL CONSTRAINT ck_curso_semestre CHECK (semestre BETWEEN 1 AND 10),
  grupo               VARCHAR(5)    NULL,
  jornada             VARCHAR(15)   NULL,
  intensidad_horaria  NUMERIC(5, 1) NULL CONSTRAINT ck_curso_ih CHECK (intensidad_horaria >= 0),
  creditos            SMALLINT      NULL CONSTRAINT ck_curso_creditos CHECK (creditos BETWEEN 0 AND 255),
  estudiantes         SMALLINT      NULL CONSTRAINT ck_curso_estudiantes CHECK (estudiantes >= 0),
  modalidad           VARCHAR(15)   NULL
);

/* Descargas y actividades administrativas: misma forma, distinta clase. */
CREATE TABLE aa.actividad (
  id                  UUID          NOT NULL CONSTRAINT pk_actividad PRIMARY KEY,
  docente_asignado_id UUID          NOT NULL CONSTRAINT fk_actividad_da REFERENCES aa.docente_asignado (id) ON DELETE CASCADE,
  clase               VARCHAR(15)   NOT NULL CONSTRAINT ck_actividad_clase CHECK (clase IN ('DESCARGA', 'ADMINISTRATIVA')),
  orden               SMALLINT      NOT NULL,
  -- NULL mientras el borrador no elige rol. Sin ON DELETE: los roles no se
  -- borran, se dejan de ofrecer (rol.vigente).
  rol_id              INT           NULL CONSTRAINT fk_actividad_rol REFERENCES aa.rol (id),
  horas               NUMERIC(5, 1) NOT NULL CONSTRAINT ck_actividad_horas CHECK (horas >= 0)
);

/*
  Los cursos tal como se aprobaron la primera vez (SPEC-009): lo proyectado.
  Sin FK a docente_asignado a propósito: los docentes se reescriben en cada
  guardado y la línea base tiene que sobrevivirlo. Solo se inserta.
*/
CREATE TABLE aa.linea_base_curso (
  asignacion_id      UUID          NOT NULL CONSTRAINT fk_lbc_asignacion REFERENCES aa.asignacion (id) ON DELETE CASCADE,
  orden              SMALLINT      NOT NULL,
  curso_id           UUID          NOT NULL,
  docente_id         UUID          NOT NULL,  -- el docente_asignado de entonces
  docente            VARCHAR(150)  NULL,
  codigo_curso       VARCHAR(20)   NULL,
  nombre_curso       VARCHAR(150)  NULL,
  semestre           SMALLINT      NULL,
  grupo              VARCHAR(5)    NULL,
  intensidad_horaria NUMERIC(5, 1) NULL,
  estudiantes        SMALLINT      NULL,
  CONSTRAINT pk_linea_base_curso PRIMARY KEY (asignacion_id, orden)
);

/* ─────────────────────────────── Novedades ──────────────────────────────── */

CREATE TABLE aa.novedad (
  id                       UUID         NOT NULL CONSTRAINT pk_novedad PRIMARY KEY,
  numero                   INT          NOT NULL CONSTRAINT uq_novedad_numero UNIQUE,
  fecha                    TIMESTAMPTZ  NOT NULL,
  autor                    VARCHAR(150) NOT NULL,  -- el nombre que tenía al hacerlo
  rol_autor                VARCHAR(12)  NOT NULL CONSTRAINT ck_novedad_rol CHECK (rol_autor IN ('ADMIN', 'COORDINADOR')),
  periodo                  CHAR(6)      NULL CONSTRAINT fk_novedad_periodo REFERENCES aa.periodo (codigo),
  con_convocatoria_cerrada BOOLEAN      NOT NULL,
  motivo                   TEXT         NOT NULL CONSTRAINT ck_novedad_motivo CHECK (length(motivo) > 0)
);

CREATE TABLE aa.novedad_cambio (
  novedad_id UUID         NOT NULL CONSTRAINT fk_nc_novedad REFERENCES aa.novedad (id),
  orden      SMALLINT     NOT NULL,
  ambito     VARCHAR(10)  NOT NULL CONSTRAINT ck_nc_ambito CHECK (ambito IN ('regla', 'limite', 'rol')),
  parametro  VARCHAR(200) NOT NULL,
  antes      VARCHAR(200) NULL,  -- NULL: no existía
  despues    VARCHAR(200) NULL,  -- NULL: se eliminó
  CONSTRAINT pk_novedad_cambio PRIMARY KEY (novedad_id, orden),
  CONSTRAINT ck_nc_hay_cambio CHECK (antes IS NOT NULL OR despues IS NOT NULL)
);

/*
  La foto: cómo estaba la asignación al aplicar el cambio. Sin FK a
  asignacion a propósito: la foto debe sobrevivir aunque la asignación se
  elimine después, y por eso copia programa, facultad y periodo.
*/
CREATE TABLE aa.novedad_afectacion (
  novedad_id    UUID         NOT NULL CONSTRAINT fk_na_novedad REFERENCES aa.novedad (id),
  asignacion_id UUID         NOT NULL,
  -- El orden en que se registraron: la novedad las lista así.
  secuencia     BIGINT       GENERATED ALWAYS AS IDENTITY,
  programa      VARCHAR(120) NOT NULL,
  facultad      VARCHAR(80)  NOT NULL,
  periodo       CHAR(6)      NOT NULL,
  errores_antes INT          NOT NULL,
  errores_ahora INT          NOT NULL,
  CONSTRAINT pk_novedad_afectacion PRIMARY KEY (novedad_id, asignacion_id),
  CONSTRAINT ck_na_empeora CHECK (errores_ahora > errores_antes)
);

CREATE TABLE aa.novedad_afectacion_docente (
  novedad_id    UUID         NOT NULL,
  asignacion_id UUID         NOT NULL,
  orden         SMALLINT     NOT NULL,
  nombres       VARCHAR(150) NOT NULL,
  motivos       JSONB        NOT NULL CONSTRAINT ck_nad_motivos CHECK (jsonb_typeof(motivos) = 'array'),  -- arreglo de textos
  CONSTRAINT pk_novedad_afectacion_docente PRIMARY KEY (novedad_id, asignacion_id, orden),
  CONSTRAINT fk_nad_afectacion FOREIGN KEY (novedad_id, asignacion_id)
    REFERENCES aa.novedad_afectacion (novedad_id, asignacion_id)
);

CREATE TABLE aa.novedad_decision (
  id            INT GENERATED ALWAYS AS IDENTITY CONSTRAINT pk_novedad_decision PRIMARY KEY,
  novedad_id    UUID         NOT NULL,
  asignacion_id UUID         NOT NULL,
  accion        VARCHAR(12)  NOT NULL CONSTRAINT ck_nd_accion CHECK (accion IN ('reabierta', 'sin_accion')),
  fecha         TIMESTAMPTZ  NOT NULL,
  autor         VARCHAR(150) NOT NULL,
  nota          TEXT         NULL,
  plazo         TIMESTAMPTZ  NULL,
  CONSTRAINT fk_nd_afectacion FOREIGN KEY (novedad_id, asignacion_id)
    REFERENCES aa.novedad_afectacion (novedad_id, asignacion_id),
  -- Reabrir exige plazo; no reabrir no lo lleva.
  CONSTRAINT ck_nd_plazo CHECK (
    (accion = 'reabierta' AND plazo IS NOT NULL) OR (accion = 'sin_accion' AND plazo IS NULL))
);

/* ────────────────────────────── Bitácora ────────────────────────────────── */

CREATE TABLE aa.evento_asignacion (
  id            UUID         NOT NULL CONSTRAINT pk_evento PRIMARY KEY,
  asignacion_id UUID         NOT NULL CONSTRAINT fk_evento_asignacion REFERENCES aa.asignacion (id) ON DELETE CASCADE,
  -- El orden de inserción: la fecha sola empataría eventos del mismo milisegundo.
  secuencia     BIGINT       GENERATED ALWAYS AS IDENTITY,
  tipo          VARCHAR(30)  NOT NULL CONSTRAINT ck_evento_tipo CHECK (tipo IN (
                  'creada', 'enviada', 'revision_abierta', 'aprobada',
                  'devuelta', 'reabierta_por_parametros', 'reenviada')),
  fecha         TIMESTAMPTZ  NOT NULL,
  autor         VARCHAR(150) NOT NULL,
  rol_autor     VARCHAR(12)  NOT NULL CONSTRAINT ck_evento_rol CHECK (rol_autor IN ('ADMIN', 'COORDINADOR')),
  nota          TEXT         NULL,
  plazo         TIMESTAMPTZ  NULL,
  version       INT          NULL,
  -- La novedad que motivó una reapertura por parámetros.
  novedad_id    UUID         NULL CONSTRAINT fk_evento_novedad REFERENCES aa.novedad (id),
  CONSTRAINT ck_evento_novedad CHECK (novedad_id IS NULL OR tipo = 'reabierta_por_parametros')
);

CREATE INDEX ix_evento_asignacion ON aa.evento_asignacion (asignacion_id, fecha);
CREATE INDEX ix_asignacion_periodo ON aa.asignacion (periodo, estado);
CREATE INDEX ix_da_asignacion ON aa.docente_asignado (asignacion_id, orden);

/* ─────────────────────── Solo se añade: bitácora y novedades ────────────── */
/*
  Un trigger y no solo permisos: REVOKE no alcanza al dueño de las tablas, y
  el valor de estos registros está en que nadie —tampoco un administrador
  de la base— pueda reescribir lo que pasó sin dejar de hacerlo a propósito
  (ALTER TABLE … DISABLE TRIGGER es un acto explícito).

  Excepción deliberada: la bitácora y la línea base se borran en cascada con
  su asignación. Un expediente sin asignación no tiene de qué dar cuenta; lo
  que no puede pasar es que se reescriba. Por eso ahí el trigger es solo de
  UPDATE: uno de DELETE también frenaría la cascada.
*/
CREATE FUNCTION aa.solo_insert() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION '%', TG_ARGV[0] USING ERRCODE = 'P0001';
END;
$$;

CREATE TRIGGER tr_evento_solo_insert BEFORE UPDATE ON aa.evento_asignacion
  FOR EACH STATEMENT EXECUTE FUNCTION aa.solo_insert('La bitácora solo admite inserciones.');

CREATE TRIGGER tr_linea_base_solo_insert BEFORE UPDATE ON aa.linea_base_curso
  FOR EACH STATEMENT EXECUTE FUNCTION aa.solo_insert('La línea base de la proyección no se modifica.');

CREATE TRIGGER tr_novedad_solo_insert BEFORE UPDATE OR DELETE ON aa.novedad
  FOR EACH STATEMENT EXECUTE FUNCTION aa.solo_insert('Las novedades no se editan ni se borran.');

CREATE TRIGGER tr_novedad_cambio_solo_insert BEFORE UPDATE OR DELETE ON aa.novedad_cambio
  FOR EACH STATEMENT EXECUTE FUNCTION aa.solo_insert('Las novedades no se editan ni se borran.');

CREATE TRIGGER tr_novedad_afectacion_solo_insert BEFORE UPDATE OR DELETE ON aa.novedad_afectacion
  FOR EACH STATEMENT EXECUTE FUNCTION aa.solo_insert('Las novedades no se editan ni se borran.');

CREATE TRIGGER tr_novedad_afectacion_docente_solo_insert BEFORE UPDATE OR DELETE ON aa.novedad_afectacion_docente
  FOR EACH STATEMENT EXECUTE FUNCTION aa.solo_insert('Las novedades no se editan ni se borran.');

CREATE TRIGGER tr_novedad_decision_solo_insert BEFORE UPDATE OR DELETE ON aa.novedad_decision
  FOR EACH STATEMENT EXECUTE FUNCTION aa.solo_insert('Las decisiones solo se suman.');

/* ───────────────────────── Rol de la aplicación ─────────────────────────── */
/*
  La aplicación se conecta con un usuario miembro de este rol, no con el
  dueño de las tablas (ver DESPLIEGUE.md):
    CREATE ROLE app_asignacion LOGIN PASSWORD '…' IN ROLE rol_asignacion_app;
  Los roles son del clúster, no de la base: si ya existe se reutiliza.
*/
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'rol_asignacion_app') THEN
    CREATE ROLE rol_asignacion_app NOLOGIN;
  END IF;
END
$$;

GRANT USAGE ON SCHEMA aa TO rol_asignacion_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA aa TO rol_asignacion_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA aa TO rol_asignacion_app;
REVOKE UPDATE, DELETE ON aa.novedad                    FROM rol_asignacion_app;
REVOKE UPDATE, DELETE ON aa.novedad_cambio             FROM rol_asignacion_app;
REVOKE UPDATE, DELETE ON aa.novedad_afectacion         FROM rol_asignacion_app;
REVOKE UPDATE, DELETE ON aa.novedad_afectacion_docente FROM rol_asignacion_app;
REVOKE UPDATE, DELETE ON aa.novedad_decision           FROM rol_asignacion_app;
REVOKE UPDATE         ON aa.evento_asignacion          FROM rol_asignacion_app;
REVOKE UPDATE         ON aa.linea_base_curso           FROM rol_asignacion_app;
